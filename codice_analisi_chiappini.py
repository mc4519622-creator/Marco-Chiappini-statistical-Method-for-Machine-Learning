def epsilonGreedy(choice, params, mosse, eps):
    path = []
    idx = mosse
    score = 0
    mean = 0
    while(mosse > 0):
        x_ = np.random.randint(0,4)
        x__= np.random.randint(0,4)
        if ( params[x_] > params[x__] and params[x_] > eps ):
            path.insert(mosse, choice[x_])
            score = score + choice[x_]
            mean = mean + params[x_]
        else:
            path.insert(mosse, choice[x__])
            score = score + choice[x__]
            mean = mean + params[x__]
        mean = mean / idx
        mosse = mosse - 1
    mean / idx
    return mean,score, path
