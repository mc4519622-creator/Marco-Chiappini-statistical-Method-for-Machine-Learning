def gradient_descent(starting_point, learning_rate, num_iterations):
    history_points.append(starting_point)
    history_values.append(f(starting_point))
    current_point = starting_point
    for i in range(num_iterations):
        gradient = f_(current_point)
        current_point = current_point - learning_rate * gradient

        history_points.append(current_point)
        history_values.append(f(current_point))
    return history_points, history_values

