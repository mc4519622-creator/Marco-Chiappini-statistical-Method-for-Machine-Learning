def RegressionePolinomiale ( a_n, x_n, degreeOfPoly): #Regressione polinomiale su coppie di liste successioni di coeff
                                                      #e di variabili secondo polinomio
    acc = 0
    for x in range(0,degreeOfPoly):
        acc = acc + a_n[x] * x_n[x] ** x
    return acc

